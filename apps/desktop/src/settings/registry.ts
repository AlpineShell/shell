const SECTIONS_BY_ID = new Map(SETTINGS_SECTIONS.map((section) => [section.id, section]))

const PAGES_BY_ID = new Map(SETTINGS_PAGES.map((page) => [page.id, page]))

const PAGES_BY_ROUTE = new Map(
  SETTINGS_PAGES.filter((page) => page.route !== null).map((page) => [page.route as string, page])
)

export function settingsSectionLabel(id: SettingsSectionId | null): string {
  if (id === null) return ''
  return SECTIONS_BY_ID.get(id)?.label ?? ''
}

export function settingsPage(id: SettingsPageId): SettingsPage | null {
  return PAGES_BY_ID.get(id) ?? null
}

export function settingsPageByRoute(route: string): SettingsPage | null {
  return PAGES_BY_ROUTE.get(route) ?? null
}

export function settingsPageRoute(id: SettingsPageId): string | null {
  return PAGES_BY_ID.get(id)?.route ?? null
}

function toTimeFormat(value: unknown): TimeFormat {
  return value === '12h' || value === '24h' ? value : 'auto'
}

const DEFAULT_TIME_FORMAT: ResolvedTimeFormat = '24h'

function toOfferedTimeFormat(value: unknown): ResolvedTimeFormat {
  return value === '12h' || value === '24h' ? value : DEFAULT_TIME_FORMAT
}

function chosenTimeFormat(prefs: ClockPrefs | null): ResolvedTimeFormat {
  return prefs ? resolveTimeFormat(prefs) : DEFAULT_TIME_FORMAT
}

function toCalendarDayCount(value: unknown): CalendarDayCount {
  return value === 2 || value === 3 ? value : 1
}

function toTilingMode(value: unknown): TilingMode {
  return value === 'dynamic' ? 'dynamic' : 'snap'
}

function toTilingDynamicLayout(value: unknown): TilingDynamicLayout {
  return value === 'columns' || value === 'master-stack' ? value : 'bsp'
}

function toOversizedPlacement(value: unknown): string {
  return value === 'center' ? 'center' : 'edge'
}

function toBatterySaverForced(value: unknown): boolean {
  return value === true
}

function toTopBarColorOverride(value: unknown): TopBarColor | null {
  if (!value || typeof value !== 'object') return null
  const candidate = value as Partial<TopBarColor>
  if (typeof candidate.r !== 'number' || typeof candidate.g !== 'number' || typeof candidate.b !== 'number') return null
  return { r: candidate.r, g: candidate.g, b: candidate.b, darkText: candidate.darkText === true }
}

function refuseUnboundHotkey(result: HotkeyBindResult): HotkeyBindResult {
  if (!result.ok) throw new Error('Alpine could not use that shortcut. Search still opens with the old one — try another combination.')
  return result
}

function freezeAutomaticTopBarColor(): Promise<unknown> {
  return window.topbar.color().then((color) => {
    if (!color) return null
    return window.topbar.setColorOverride({ r: color.r, g: color.g, b: color.b })
  })
}

