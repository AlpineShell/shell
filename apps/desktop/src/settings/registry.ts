const ENTRIES_BY_ID = new Map(SETTINGS_REGISTRY.map((entry) => [entry.id, entry]))

export function settingsEntry(id: string): SettingsEntry | null {
  return ENTRIES_BY_ID.get(id) ?? null
}

export function isSettingsValueEntry(entry: SettingsEntry): entry is SettingsValueEntry {
  return 'read' in entry
}

export function settingsEntryHint(entry: SettingsEntry): string {
  return entry.hint ?? entry.description
}
